-- Revisão de segurança 4 (R4-1): endereços (IP ou bloco /64 IPv6) de onde cada conta já entrou com sucesso.
-- Durante um ataque distribuído (teto de falhas da conta estourado), só eles continuam podendo tentar o login:
-- o atacante não ganha tentativas ilimitadas trocando de IP, e o dono não fica trancado do lugar de sempre.
-- Dado pessoal (IP): 90 dias e no máximo 10 por conta; apagado junto com a conta (anonimização).
CREATE TABLE trusted_login_sources (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT       NOT NULL REFERENCES users (id),
    source_key      VARCHAR(64)  NOT NULL,
    last_success_at TIMESTAMP    NOT NULL,
    CONSTRAINT uk_trusted_login_sources UNIQUE (user_id, source_key)
);
