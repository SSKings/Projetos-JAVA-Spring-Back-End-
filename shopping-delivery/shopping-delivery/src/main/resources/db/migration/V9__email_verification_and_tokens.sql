-- E-mail transacional (ADR-025): confirmação do e-mail e links de uso único (confirmar e-mail, redefinir senha).
-- O token nunca é guardado: só o SHA-256 dele (quem lê o banco não consegue usar um link pendente).
ALTER TABLE users ADD COLUMN email_verified_at TIMESTAMP;

CREATE TABLE email_tokens (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT       NOT NULL REFERENCES users (id),
    purpose     VARCHAR(20)  NOT NULL,
    token_hash  VARCHAR(64)  NOT NULL UNIQUE,
    created_at  TIMESTAMP    NOT NULL,
    expires_at  TIMESTAMP    NOT NULL,
    used_at     TIMESTAMP
);
-- "último link deste tipo para esta conta" (intervalo mínimo entre envios) e invalidação dos anteriores
CREATE INDEX IF NOT EXISTS idx_email_tokens_user_purpose ON email_tokens (user_id, purpose, created_at);
